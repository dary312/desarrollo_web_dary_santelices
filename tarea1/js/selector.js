const obtenerFechaRellenar = () => {
  const hora_rellenar = new Date();
  hora_rellenar.setHours(hora_rellenar.getHours() + 3);

  const año = hora_rellenar.getFullYear();
  const mes = String(hora_rellenar.getMonth() + 1).padStart(2, '0');
  const dia = String(hora_rellenar.getDate()).padStart(2, '0');
  const hora = String(hora_rellenar.getHours()).padStart(2, '0'); 
  const minuto = String(hora_rellenar.getMinutes()).padStart(2, '0');

    
  return `${año}-${mes}-${dia}T${hora}:${minuto}`;
}

const rellenarEntrega = () => {
  const horaEntrega = document.getElementById("fecha_entrega");
  horaEntrega.defaultValue = obtenerFechaRellenar();
}

